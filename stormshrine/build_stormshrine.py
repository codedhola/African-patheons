class MB:
    def __init__(self):
        self.v = []      # Vector
        self.f = []      # [vid, ...]
        self.fuv = []    # [(u, v), ...] per face corner
        self.fm = []     # material name
        self.fs = []     # smooth flag
        self.fi = []     # island id
        self.nisl = 0

    def island(self):
        self.nisl += 1
        return self.nisl

    def vert(self, co):
        self.v.append(Vector(co))
        return len(self.v) - 1

    def face(self, vids, uvs, mat, smooth, isl):
        assert len(vids) == len(uvs) and len(set(vids)) == len(vids), (vids, mat)
        self.f.append(list(vids))
        self.fuv.append([tuple(u) for u in uvs])
        self.fm.append(mat)
        self.fs.append(smooth)
        self.fi.append(isl)

    def merge(self, o):
        base, ib = len(self.v), self.nisl
        self.v += [v.copy() for v in o.v]
        for f, uv, m, s, i in zip(o.f, o.fuv, o.fm, o.fs, o.fi):
            self.f.append([x + base for x in f])
            self.fuv.append(list(uv))
            self.fm.append(m)
            self.fs.append(s)
            self.fi.append(i + ib)
        self.nisl += o.nisl
        return self

    def transform(self, M):
        self.v = [M @ v for v in self.v]
        return self

    # --- UV post-processing -------------------------------------------------
    def fix_mirrored_islands(self):
        """Flip u on islands whose UV winding is opposite to the face winding,
        so no island is mirrored (keeps tangent-space normal maps correct)."""
        area = {}
        for uvs, i in zip(self.fuv, self.fi):
            area[i] = area.get(i, 0.0) + signed_area(uvs)
        flip = {i for i, a in area.items() if a < 0}
        self.fuv = [[(-u, v) for u, v in uvs] if i in flip else uvs for uvs, i in zip(self.fuv, self.fi)]

    def pack(self, gap=0.04, snap=None):
        """Shelf-pack island bounding boxes without scaling (keeps metres).
        snap=(su, sv): only move islands by whole multiples (for non-tiling UVs)."""
        self.fix_mirrored_islands()
        boxes = {}
        for uvs, i in zip(self.fuv, self.fi):
            b = boxes.setdefault(i, [1e9, 1e9, -1e9, -1e9])
            for u, v in uvs:
                b[0], b[1] = min(b[0], u), min(b[1], v)
                b[2], b[3] = max(b[2], u), max(b[3], v)
        items = sorted(boxes.items(), key=lambda kv: -(kv[1][3] - kv[1][1]))
        total = sum((b[2] - b[0] + gap) * (b[3] - b[1] + gap) for _, b in items)
        row_w = max(max(b[2] - b[0] for _, b in items), math.sqrt(total) * 1.25)

        def snapped(pos, lo, s):
            return pos - lo if not s else math.ceil((pos - lo) / s - 1e-9) * s
        x = y = row_h = 0.0
        off = {}
        for i, b in items:
            w, h = b[2] - b[0], b[3] - b[1]
            if x > 0 and x + w > row_w:
                x, y, row_h = 0.0, y + row_h + gap, 0.0
            du = snapped(x, b[0], snap and snap[0])
            dv = snapped(y, b[1], snap and snap[1])
            off[i] = (du, dv)
            x = b[0] + du + w + gap
            row_h = max(row_h, b[1] + dv + h - y)
        self.fuv = [[(u + off[i][0], v + off[i][1]) for u, v in uvs] for uvs, i in zip(self.fuv, self.fi)]


