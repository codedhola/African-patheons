ALT_K = 1.10 / 82.0     # altar: the drawn odó is 82 px tall (y 594..676) -> 1.10 m


def altar_outer_profile():
    """Outer silhouette of the odó from SVG path M676 676 L684 646 C690 636 692 624 688 614 L680 594 ...
    in (r, z) with r = |x - 720| and z = 676 - y."""
    pts = [(44.0, 0.0), (36.0, 30.0)]
    P = [(36.0, 30.0), (30.0, 40.0), (28.0, 52.0), (32.0, 62.0)]
    pts += [bez(P, k / 6) for k in range(1, 7)]
    pts.append((40.0, 82.0))
    return [(r * ALT_K, z * ALT_K) for r, z in pts]


def build_altar(coll):
    """Stormshrine_Altar: the odó Ṣàngó, a carved mortar (wide foot, waist,
    flared cup) with white relief: oṣé front and back, zigzag snake round the
    foot, a dog on each side (docs/fighting-stages.md: double-axe, dog and
    zigzag-snake reliefs)."""
    mb = MB()
    wood, dark, W = ASSET_PREFIX + 'Wood_Carved', ASSET_PREFIX + 'Wood_Dark', ASSET_PREFIX + 'Kaolin_White'
    outer = altar_outer_profile()
    r_top = outer[-1][0]
    cavity = [(r_top - 0.012, 1.104), (0.47, 1.10), (0.445, 1.0), (0.39, 0.92), (0.30, 0.87), (0.15, 0.852), (0.0, 0.85)]
    prof = outer + cavity
    mats = [wood] * (len(outer) - 1) + [wood] + [dark] * (len(cavity) - 1)
    lathe(mb, prof, 40, mats, smooth=True, theta0=0.0)
    rz = [(z, r) for r, z in outer]
    rfun = lambda z: interp(rz, z)
    cx, cy = ALTAR_POS
    # SVG altar emblem: bar y 612..636, lobes C 710 612, 710 628 (scale ALT_K, base y 676)
    def emblem(theta):
        z_mid = (676 - 624) * ALT_K
        fm = revolution_map((0, 0, 0), rfun, theta, rfun(z_mid))
        bar = [(0.0, (676 - 636) * ALT_K), (0.0, (676 - 612) * ALT_K)]
        relief_stroke(mb, bar, 0.040, 0.015, fm, W, samples=4)
        for sgn, h in ((1, 0.011), (-1, 0.013)):      # 2 mm apart where the lobe ends overlap
            lobe = [(sgn * (x - 720) * ALT_K, (676 - y) * ALT_K)
                    for x, y in bez_path([((720, 618), (710, 612), (710, 628), (720, 626))], 10)]
            relief_stroke(mb, lobe, 0.034, h, fm, W)
    emblem(-math.pi / 2)        # front (faces -Y)
    emblem(math.pi / 2)         # back
    # zigzag snake band round the foot (SVG y 652..660)
    z_lo, z_hi = (676 - 660) * ALT_K, (676 - 652) * ALT_K
    r_ref = rfun((z_lo + z_hi) / 2)
    teeth = 15
    circ = 2 * math.pi * r_ref
    band = [(circ * k / (2 * teeth), z_lo if k % 2 == 0 else z_hi) for k in range(2 * teeth)]
    relief_stroke(mb, band, 0.032, 0.011, revolution_map((0, 0, 0), rfun, -math.pi / 2, r_ref), W, closed=True,
                  samples=3)
    # dogs on the flanks, both walking toward the front
    dog = [(0.12, 0.0), (0.20, 0.0), (0.21, 0.22), (0.62, 0.22), (0.63, 0.0), (0.71, 0.0), (0.72, 0.30),
           (0.80, 0.38), (0.95, 0.40), (1.00, 0.46), (0.92, 0.52), (0.86, 0.56), (0.84, 0.66), (0.79, 0.57),
           (0.74, 0.52), (0.66, 0.46), (0.22, 0.46), (0.14, 0.50), (0.04, 0.68), (0.02, 0.64), (0.11, 0.44),
           (0.10, 0.30)]
    for theta, mirror in ((0.0, True), (math.pi, False)):
        zc = 0.62
        fm = revolution_map((0, 0, 0), rfun, theta, rfun(zc))
        L = 0.34
        pts = [(((1 - x) if mirror else x) - 0.5) * L for x, _ in dog]
        out = [(px_, zc + (y - 0.33) * L) for px_, (_, y) in zip(pts, dog)]
        relief_fill(mb, out, 0.012, fm, W)
    mb.transform(translate(cx, cy))
    return mb_to_object(mb, ASSET_PREFIX + 'Altar', coll)


