def collection(name, parent=None):
    c = bpy.data.collections.new(name)
    (parent or bpy.context.scene.collection).children.link(c)
    COLL[name] = c
    return c


def mb_to_object(mb, name, coll, pack=True, sharp_angle=35.0, snap=None):
    if pack:
        mb.pack(snap=snap)
    me = bpy.data.meshes.new(name)
    me.from_pydata([tuple(v) for v in mb.v], [], [tuple(f) for f in mb.f])
    uvl = me.uv_layers.new(name='UVMap')
    uvl.data.foreach_set('uv', [c for uvs in mb.fuv for uv in uvs for c in uv])
    names = []
    for m in mb.fm:
        if m not in names:
            names.append(m)
    for m in names:
        me.materials.append(MATS[m])
    me.polygons.foreach_set('material_index', [names.index(m) for m in mb.fm])
    me.polygons.foreach_set('use_smooth', [bool(s) for s in mb.fs])
    if me.validate(verbose=False):
        print('  !! mesh %s needed validation fixes' % name)
    me.update()
    if any(mb.fs):
        me.set_sharp_from_angle(angle=math.radians(sharp_angle))
    ob = bpy.data.objects.new(name, me)
    coll.objects.link(ob)
    ASSET_OBJECTS.append(ob)
    return ob


def bm_to_object(bm, name, coll, mat):
    me = bpy.data.meshes.new(name)
    bm.to_mesh(me)
    bm.free()
    me.materials.append(MATS[mat])
    ob = bpy.data.objects.new(name, me)
    coll.objects.link(ob)
    smart_uv_metres(ob)
    ASSET_OBJECTS.append(ob)
    return ob


def activate(ob):
    for o in bpy.context.view_layer.objects:
        o.select_set(False)
    bpy.context.view_layer.objects.active = ob
    ob.select_set(True)


def smart_uv_metres(ob):
    """Smart UV Project (no overlaps), then scale islands so 1 UV unit = 1 m."""
    activate(ob)
    me = ob.data
    if not me.uv_layers:
        me.uv_layers.new(name='UVMap')
    bpy.ops.object.mode_set(mode='EDIT')
    bpy.ops.mesh.select_all(action='SELECT')
    bpy.ops.uv.smart_project(angle_limit=math.radians(60), island_margin=0.03, scale_to_bounds=False)
    bpy.ops.object.mode_set(mode='OBJECT')
    a3 = sum(p.area for p in me.polygons)
    uv = me.uv_layers['UVMap'].data
    auv = 0.0
    for p in me.polygons:
        pts = [uv[li].uv for li in p.loop_indices]
        auv += abs(signed_area([(q.x, q.y) for q in pts]))
    k = math.sqrt(a3 / max(auv, 1e-12))
    for d in uv:
        d.uv = d.uv * k


def add_lightmap_uv(ob):
    me = ob.data
    lm = me.uv_layers.new(name='UVLightmap', do_init=True)
    me.uv_layers.active = lm
    activate(ob)
    bpy.ops.object.mode_set(mode='EDIT')
    bpy.ops.mesh.select_all(action='SELECT')
    bpy.ops.uv.select_all(action='SELECT')
    bpy.ops.uv.pack_islands(rotate=True, scale=True, margin_method='SCALED', margin=0.004)
    bpy.ops.object.mode_set(mode='OBJECT')
    me.uv_layers.active = me.uv_layers['UVMap']
    me.uv_layers['UVMap'].active_render = True


