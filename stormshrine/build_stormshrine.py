def door_arch_points(n=10):
    """Arch points (x, z) from the left spring to the right spring."""
    return [(svg_x(x), Z0 + svg_h(y)) for x, y in (bez(DOOR_ARCH, k / n) for k in range(n + 1))]


def build_base(coll):
    """Stormshrine_Base: earthen platform (0.30 m) with one 0.15 m step at the door."""
    bm = bmesh.new()

    def block(x0, x1, y0, y1, z1, bevel_sel, offset):
        """Box from the ground up to z1; bevel the edges bevel_sel picks."""
        c = [(x0, y0, 0), (x1, y0, 0), (x1, y1, 0), (x0, y1, 0), (x0, y0, z1), (x1, y0, z1), (x1, y1, z1), (x0, y1, z1)]
        v = [bm.verts.new(p) for p in c]
        for f in ((0, 3, 2, 1), (4, 5, 6, 7), (0, 1, 5, 4), (1, 2, 6, 5), (2, 3, 7, 6), (3, 0, 4, 7)):
            bm.faces.new([v[i] for i in f])
        bm.edges.ensure_lookup_table()
        edges = [e for e in bm.edges if set(e.verts) <= set(v) and bevel_sel(e)]
        bmesh.ops.bevel(bm, geom=edges, offset=offset, offset_type='OFFSET', segments=2, profile=0.5,
                        affect='EDGES', clamp_overlap=True)

    hx, hy = HALF_W + APRON, HALF_D + APRON
    is_top = lambda e: all(abs(x.co.z - PLINTH_H) < 1e-6 for x in e.verts)
    is_vert = lambda e: abs(e.verts[0].co.z - e.verts[1].co.z) > 1e-6
    block(-hx, hx, -hy, hy, PLINTH_H, lambda e: is_top(e) or is_vert(e), 0.06)
    # the step: round its front and side top edges and front corners, not the edge against the platform
    sx = 1.30
    sy0, sy1 = -hy - 0.35, -hy
    in_step = lambda e: all(x.co.y <= sy1 + 1e-6 and abs(x.co.x) <= sx + 1e-6 for x in e.verts)
    step_sel = lambda e: in_step(e) and (
        (all(abs(x.co.z - STEP_H) < 1e-6 for x in e.verts) and not all(abs(x.co.y - sy1) < 1e-6 for x in e.verts))
        or (is_vert(e) and all(abs(x.co.y - sy0) < 1e-6 for x in e.verts)))
    block(-sx, sx, sy0, sy1, STEP_H, step_sel, 0.035)
    # remove hidden faces: undersides on the ground and the step's back against the platform
    bm.normal_update()
    dead = [f for f in bm.faces if f.calc_center_median().z < 1e-6 and f.normal.z < -0.99]
    dead += [f for f in bm.faces if abs(f.calc_center_median().y - sy1) < 1e-6 and f.normal.y > 0.99
             and f.calc_center_median().z < STEP_H]
    bmesh.ops.delete(bm, geom=dead, context='FACES_ONLY')
    return bm_to_object(bm, ASSET_PREFIX + 'Base', coll, ASSET_PREFIX + 'EarthPlaster')


def wall_outline_outer():
    """Outer plan outline (CCW) with the door columns on the front straight.
    Returns [(x, y, kind, z_arch)]; kind 'full' or 'arch'."""
    r = CORNER_R
    pts = [(-(HALF_W - r), -HALF_D, 'full', None), (-DOOR_HW, -HALF_D, 'full', None)]
    arch = door_arch_points()
    for x, z in arch[1:-1]:
        pts.append((x, -HALF_D, 'arch', z))
    pts.append((DOOR_HW, -HALF_D, 'full', None))
    for x, y in rrect(HALF_W, HALF_D, r, 1, 1, 4)[1:]:
        pts.append((x, y, 'full', None))
    return pts


def build_walls(coll):
    """Stormshrine_Walls: 0.4 m mud walls, open top (under the roof) and bottom
    (on the platform). Outside red plaster, inside earth plaster, arch soffit white."""
    mb = MB()
    zs = Z0 + svg_h(578)
    red, earth, white = ASSET_PREFIX + 'MudPlaster_Red', ASSET_PREFIX + 'EarthPlaster', ASSET_PREFIX + 'Kaolin_White'
    rows_full = [Z0, zs, Z1]

    def surface(outline, inward, mat, isl_v0):
        isl = mb.island()
        cols = []
        for x, y, kind, za in outline:
            rows = rows_full if kind == 'full' else [za, Z1]
            cols.append({z: mb.vert((x, y, z)) for z in rows})
        n = len(outline)
        u = [0.0]
        for k in range(n):
            a, b = outline[k], outline[(k + 1) % n]
            u.append(u[-1] + math.hypot(b[0] - a[0], b[1] - a[1]))
        for k in range(n):
            k1 = (k + 1) % n
            A, B = cols[k], cols[k1]
            ka, kb = outline[k][2], outline[k1][2]
            if ka == 'full' and kb == 'full':
                spans = [(Z0, zs, Z0, zs), (zs, Z1, zs, Z1)]
            else:   # over the door: from the arch up to the wall top, nothing below
                za = outline[k][3] if ka == 'arch' else zs
                zb = outline[k1][3] if kb == 'arch' else zs
                spans = [(za, Z1, zb, Z1)]
            for (a0, a1, b0, b1) in spans:
                quad = [A[a0], B[b0], B[b1], A[a1]]
                uvq = [(u[k], a0 - Z0 + isl_v0), (u[k + 1], b0 - Z0 + isl_v0), (u[k + 1], b1 - Z0 + isl_v0),
                       (u[k], a1 - Z0 + isl_v0)]
                if inward:
                    quad, uvq = quad[::-1], uvq[::-1]
                mb.face(quad, uvq, mat, False, isl)
        return cols

    outer = wall_outline_outer()
    oc = surface(outer, False, red, 0.0)
    ix, iy = HALF_W - WALL_T, HALF_D - WALL_T
    inner = [(-ix, -iy, 'full', None), (-DOOR_HW, -iy, 'full', None)]
    for x, _, kind, za in outer[2:]:
        if kind == 'arch':
            inner.append((x, -iy, 'arch', za))
    inner += [(DOOR_HW, -iy, 'full', None), (ix, -iy, 'full', None), (ix, iy, 'full', None),
              (-ix, iy, 'full', None)]
    ic = surface(inner, True, earth, 0.0)

    # door tunnel: jambs (red) and arch soffit (white: the pale band under the arch on the board)
    isl = mb.island()
    o_door = [i for i, p in enumerate(outer) if p[1] == -HALF_D and (p[2] == 'arch' or abs(abs(p[0]) - DOOR_HW) < 1e-6)]
    i_door = [i for i, p in enumerate(inner) if p[1] == -iy and (p[2] == 'arch' or abs(abs(p[0]) - DOOR_HW) < 1e-6)]
    ol, il = oc[o_door[0]], ic[i_door[0]]
    orr, irr = oc[o_door[-1]], ic[i_door[-1]]
    t = WALL_T
    mb.face([ol[Z0], il[Z0], il[zs], ol[zs]], [(0, 0), (0, t), (zs - Z0, t), (zs - Z0, 0)], red, False, isl)
    acc = zs - Z0
    seq_o = [oc[i] for i in o_door]
    seq_i = [ic[i] for i in i_door]
    ztop = lambda col: min(z for z in col if z >= zs - 1e-9)
    for k in range(len(seq_o) - 1):
        a0, a1 = seq_o[k], seq_o[k + 1]
        b0, b1 = seq_i[k], seq_i[k + 1]
        za, zb = ztop(a0), ztop(a1)
        xa, xb = outer[o_door[k]][0], outer[o_door[k + 1]][0]
        d = math.hypot(xb - xa, zb - za)
        mb.face([a0[za], b0[za], b1[zb], a1[zb]], [(acc, 0), (acc, t), (acc + d, t), (acc + d, 0)], white, False, isl)
        acc += d
    mb.face([irr[Z0], orr[Z0], orr[zs], irr[zs]], [(acc + zs - Z0, t), (acc + zs - Z0, 0), (acc, 0), (acc, t)],
            red, False, isl)
    return mb_to_object(mb, ASSET_PREFIX + 'Walls', coll)


def build_door_valance(coll):
    """Stormshrine_DoorValance: the white band under the door arch on the board
    (SVG M770 576 C790 566 810 566 830 576 L830 600 ...), read as a white cloth
    hung inside the arch. Shortened so its lower edge stays at 2.05-2.12 m and
    the doorway keeps its clearance; meant to be non-colliding cloth."""
    mb = MB()
    lo = lambda x: Z0 + 2.05 + 0.07 * (1 - (x / DOOR_HW) ** 2)   # lower edge arches up like the drawn one
    top = [(x * 0.985, z - 0.006) for x, z in door_arch_points(16)]   # just under the soffit
    top = [(x, z) for x, z in top if z >= lo(x) + 0.03]
    xl, xr = top[0][0], top[-1][0]
    outline = top + [(x, lo(x)) for x in np.linspace(xr, xl, 12)]
    extrude_shape(mb, outline, 0.012, ASSET_PREFIX + 'Cloth_White', ASSET_PREFIX + 'Cloth_White')
    mb.transform(translate(0.0, -HALF_D + 0.07, 0.0))
    return mb_to_object(mb, ASSET_PREFIX + 'DoorValance', coll)


def build_roof(coll):
    """Stormshrine_Roof: thatch rising to a single apex (the board's front
    triangle, SVG 620,528 - 800,412 - 980,528) in six stepped courses, ragged
    eave, sloped soffit back to the wall line and a flat mud ceiling inside."""
    mb = MB()
    rnd = random.Random(21)
    th = ASSET_PREFIX + 'Thatch'
    ceil = ASSET_PREFIX + 'EarthPlaster'
    NX, NY, NA = 16, 12, 4
    XE, YE = HALF_W + OVERHANG, HALF_D + OVERHANG
    RE = CORNER_R + OVERHANG
    z_eb = Z0 + EAVE_H                  # eave underside (SVG y 528)
    z_et = z_eb + 0.20                  # top of the eave fascia, before the course lip
    z_ap = Z0 + APEX_H                  # apex (SVG y 412)
    lip = 0.07
    courses = [0.0, 0.17, 0.33, 0.48, 0.63, 1.0]

    def ring(t, z_off, jitter=0.0):
        s = 1.0 - t
        z = z_et + t * (z_ap - z_et) + z_off
        return (t, z, [mb.vert((x, y, z + (rnd.uniform(-jitter, jitter) if jitter else 0.0)))
                       for x, y in rrect(XE * s, YE * s, RE * s, NX, NY, NA)])

    ring_eb = [mb.vert((x, y, z_eb - rnd.uniform(0.0, 0.07))) for x, y in rrect(XE, YE, RE, NX, NY, NA)]
    tops = [ring(0.0, lip)]                      # course butt edges step out by about `lip`
    for t in courses[1:-1]:
        tops.append(ring(t, 0.0))
        tops.append(ring(t, lip * rnd.uniform(0.8, 1.3), jitter=0.03))
    apex = mb.vert((0.0, 0.0, z_ap))
    npt = len(ring_eb)
    base2d = rrect(XE, YE, RE, NX, NY, NA)

    def side_of(k):   # classify a ring segment by its outward normal
        a, b = base2d[k], base2d[(k + 1) % npt]
        nx_, ny_ = b[1] - a[1], -(b[0] - a[0])
        ang = math.degrees(math.atan2(ny_, nx_))
        if -135 <= ang < -45:
            return 'front'
        if -45 <= ang < 45:
            return 'right'
        if 45 <= ang < 135:
            return 'back'
        return 'left'
    # One UV island per roof side: u runs along the eave, v up the slope (so the
    # thatch streaks run downhill); v is the distance along the side's centre
    # line, counting each course lip, so it always increases from ring to ring.
    side_isl = {s: mb.island() for s in ('front', 'right', 'back', 'left')}
    proj = dict(front=lambda p: p.x, back=lambda p: -p.x, right=lambda p: p.y, left=lambda p: -p.y)
    half = dict(front=YE, back=YE, right=XE, left=XE)
    vpos = {}
    for s in side_isl:
        line = [(half[s] * (1 - t), z) for t, z, _ in tops] + [(0.0, z_ap)]
        acc = [0.0]
        for a, b in zip(line, line[1:]):
            acc.append(acc[-1] + math.dist(a, b))
        vpos[s] = acc
    for r, (_, _, A) in enumerate(tops):
        Bv = tops[r + 1][2] if r + 1 < len(tops) else None
        for k in range(npt):
            k1 = (k + 1) % npt
            s = side_of(k)
            pr = proj[s]
            va, vb = vpos[s][r], vpos[s][r + 1]
            ua, ua1 = pr(mb.v[A[k]]), pr(mb.v[A[k1]])
            if Bv is None:
                mb.face([A[k], A[k1], apex], [(ua, va), (ua1, va), (0.0, vb)], th, False, side_isl[s])
            else:
                ub, ub1 = pr(mb.v[Bv[k]]), pr(mb.v[Bv[k1]])
                mb.face([A[k], A[k1], Bv[k1], Bv[k]], [(ua, va), (ua1, va), (ub1, vb), (ub, vb)], th, False,
                        side_isl[s])
    # fascia (eave edge)
    fi = mb.island()
    top0 = tops[0][2]
    acc = 0.0
    for k in range(npt):
        k1 = (k + 1) % npt
        d = (mb.v[ring_eb[k1]] - mb.v[ring_eb[k]]).length
        za, zb = mb.v[ring_eb[k]].z, mb.v[ring_eb[k1]].z
        mb.face([ring_eb[k], ring_eb[k1], top0[k1], top0[k]],
                [(acc, za), (acc + d, zb), (acc + d, z_et + lip), (acc, z_et + lip)], th, False, fi)
        acc += d
    # soffit: eave underside back to the wall line at the wall top
    wl = [mb.vert((x, y, Z1)) for x, y in rrect(HALF_W, HALF_D, CORNER_R, NX, NY, NA)]
    si = mb.island()
    acc = 0.0
    for k in range(npt):
        k1 = (k + 1) % npt
        d = (mb.v[ring_eb[k1]] - mb.v[ring_eb[k]]).length
        mb.face([ring_eb[k], wl[k], wl[k1], ring_eb[k1]], [(acc, 0), (acc, OVERHANG), (acc + d, OVERHANG), (acc + d, 0)],
                th, False, si)
        acc += d
    # flat mud ceiling over the room (also caps the wall tops)
    ci = mb.island()
    cen = mb.vert((0.0, 0.0, Z1))
    for k in range(npt):
        k1 = (k + 1) % npt
        a, b = mb.v[wl[k]], mb.v[wl[k1]]
        mb.face([cen, wl[k1], wl[k]], [(0, 0), (b.x, b.y), (a.x, a.y)], ceil, False, ci)
    return mb_to_object(mb, ASSET_PREFIX + 'Roof', coll)


def build_wall_motifs(coll):
    """Stormshrine_WallMotifs: white kaolin paint in low relief (7 mm).
    Front wall exactly as drawn: lightning zigzags at both corners (SVG 664..676
    and 924..936, y 540..640), oṣé double-axe emblems (x 712 and 888) and two
    pairs of dots under the eaves (x 700, 724, 876, 900). The unseen side and
    back walls repeat the same motifs (assumption)."""
    mb = MB()
    W = ASSET_PREFIX + 'Kaolin_White'
    H = 0.007
    eps = 0.002        # height step between strokes that overlap (>1 mm, so they never z-fight)

    def zig(xs):
        return [(svg_x(x), Z0 + svg_h(y)) for x, y in zip(xs, (540, 560, 580, 600, 620, 640))]

    def ose(cx):
        bar = [(cx, Z0 + svg_h(616)), (cx, Z0 + svg_h(556))]
        lobe = lambda sgn: [(cx + sgn * (x - 712) * PX, Z0 + svg_h(y)) for x, y in
                            bez_path([((712, 566), (690, 556), (690, 586), (712, 580))], 10)]
        return bar, lobe(1), lobe(-1)

    def emblem(fmap, bar, l1, l2):
        # the lobe ends meet inside the bar: give each stroke its own height so
        # no two top faces are coplanar (the bar stands proudest)
        relief_stroke(mb, bar, 4 * PX, H + eps * 2, fmap, W)
        relief_stroke(mb, l1, 4 * PX, H, fmap, W)
        relief_stroke(mb, l2, 4 * PX, H + eps, fmap, W)

    def paint(fmap, dots_z):
        """The front wall's layout; s is the horizontal wall coordinate (SVG x)."""
        for xs in ((664, 676, 664, 676, 664, 676), (936, 924, 936, 924, 936, 924)):
            relief_stroke(mb, zig(xs), 5 * PX, H, fmap, W)
        for cx in (712, 888):
            emblem(fmap, *ose(svg_x(cx)))
        for x in (700, 724, 876, 900):
            relief_fill(mb, ellipse(svg_x(x), dots_z, 3.5 * PX, 3.5 * PX, 12), H, fmap, W)

    # dots: drawn at y 530, just under the eave line; lowered so the eave overhang doesn't hide them
    dz = Z0 + 3.10
    paint(plane_map((0, -HALF_D, 0), (1, 0, 0), (0, 0, 1)), dz)       # front (outward -Y)
    paint(plane_map((0, HALF_D, 0), (-1, 0, 0), (0, 0, 1)), dz)       # back (outward +Y)
    # sides: the same vocabulary fitted to the 6.4 m walls
    for sign in (1, -1):
        fm = plane_map((sign * HALF_W, 0, 0), (0, sign, 0), (0, 0, 1))
        inset = HALF_D - 0.54
        for s0, xs in ((-inset, (664, 676, 664, 676, 664, 676)), (inset, (936, 924, 936, 924, 936, 924))):
            centre = svg_x(670 if s0 < 0 else 930)
            pts = [(s0 + x - centre, z) for x, z in zig(xs)]
            relief_stroke(mb, pts, 5 * PX, H, fm, W)
        emblem(fm, *ose(0.0))
        for s in (-1.55, -1.0, 1.0, 1.55):
            relief_fill(mb, ellipse(s, dz, 3.5 * PX, 3.5 * PX, 12), H, fm, W)
    return mb_to_object(mb, ASSET_PREFIX + 'WallMotifs', coll)


