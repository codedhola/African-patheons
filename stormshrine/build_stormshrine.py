def tri_overlaps(tris):
    """Count overlapping UV triangle pairs (shared edges/corners don't count)."""
    from collections import defaultdict
    if not tris:
        return 0
    cell = max(1e-4, math.sqrt(sum(abs(signed_area(t)) for t in tris) / len(tris)) * 2.0)
    grid = defaultdict(list)
    boxes = []
    for i, t in enumerate(tris):
        xs, ys = [p[0] for p in t], [p[1] for p in t]
        b = (min(xs), min(ys), max(xs), max(ys))
        boxes.append(b)
        for gx in range(int(math.floor(b[0] / cell)), int(math.floor(b[2] / cell)) + 1):
            for gy in range(int(math.floor(b[1] / cell)), int(math.floor(b[3] / cell)) + 1):
                grid[(gx, gy)].append(i)
    eps = 1e-7

    def sep(a, b):
        for poly in (a, b):
            for k in range(3):
                p, q = poly[k], poly[(k + 1) % 3]
                nx_, ny_ = q[1] - p[1], p[0] - q[0]
                pa = [nx_ * x + ny_ * y for x, y in a]
                pb = [nx_ * x + ny_ * y for x, y in b]
                ln = math.hypot(nx_, ny_) or 1.0
                if max(pa) <= min(pb) + eps * ln or max(pb) <= min(pa) + eps * ln:
                    return True
        return False
    seen = set()
    count = 0
    for ids in grid.values():
        for x in range(len(ids)):
            for y in range(x + 1, len(ids)):
                i, j = ids[x], ids[y]
                if (i, j) in seen:
                    continue
                seen.add((i, j))
                bi, bj = boxes[i], boxes[j]
                if bi[2] <= bj[0] or bj[2] <= bi[0] or bi[3] <= bj[1] or bj[3] <= bi[1]:
                    continue
                if abs(signed_area(tris[i])) < 1e-12 or abs(signed_area(tris[j])) < 1e-12:
                    continue
                if not sep(tris[i], tris[j]):
                    count += 1
    return count


def validate(objs):
    rows = []
    total = 0
    for ob in objs:
        me = ob.data
        me.calc_loop_triangles()
        ntri = len(me.loop_triangles)
        total += ntri
        res = dict(name=ob.name, tris=ntri, mats=[m.name for m in me.materials])
        for layer in ('UVMap', 'UVLightmap'):
            uv = me.uv_layers[layer].data
            tris = [tuple((uv[li].uv.x, uv[li].uv.y) for li in lt.loops) for lt in me.loop_triangles]
            res['overlap_' + layer] = tri_overlaps(tris)
        bm = bmesh.new()
        bm.from_mesh(me)
        res['nonmanifold'] = sum(1 for e in bm.edges if len(e.link_faces) > 2)
        res['boundary'] = sum(1 for e in bm.edges if len(e.link_faces) == 1)
        flipped = 0
        for e in bm.edges:
            if len(e.link_faces) == 2:
                f1, f2 = e.link_faces
                l1 = [l for l in e.link_loops if l.face == f1][0]
                l2 = [l for l in e.link_loops if l.face == f2][0]
                if l1.vert == l2.vert:
                    flipped += 1
        res['inconsistent_winding'] = flipped
        res['degenerate'] = sum(1 for f in bm.faces if f.calc_area() < 1e-9)
        if res['boundary'] == 0:
            vol = bm.calc_volume(signed=True)
            res['closed_volume'] = round(vol, 5)
        bm.free()
        res['identity'] = (ob.matrix_world == Matrix.Identity(4))
        rows.append(res)
    return rows, total


