PLAN_COLOURS = dict(TRG='#3cff7a', SPAWN='#3cd6ff', VFX='#ffd23c', SFX='#ff5ad2')


def plan_overlay():
    """Temporary, render-only overlay for the plan view (added after the .blend
    is saved): trigger volumes as translucent green, marker points as discs
    (blue spawns, yellow VFX, pink SFX) and a soft top light."""
    made = []

    def glow_mat(name, hexc, alpha):
        m = bpy.data.materials.new(name)
        nt = node_tree(m)
        nt.nodes.clear()
        out = nt.nodes.new('ShaderNodeOutputMaterial')
        em = nt.nodes.new('ShaderNodeEmission')
        em.inputs['Color'].default_value = (*lin(hexc), 1)
        em.inputs['Strength'].default_value = 2.0
        tr = nt.nodes.new('ShaderNodeBsdfTransparent')
        mx = nt.nodes.new('ShaderNodeMixShader')
        mx.inputs['Fac'].default_value = alpha
        nt.links.new(tr.outputs['BSDF'], mx.inputs[1])
        nt.links.new(em.outputs['Emission'], mx.inputs[2])
        nt.links.new(mx.outputs['Shader'], out.inputs['Surface'])
        return m
    trg = glow_mat('PLAN_Trigger', PLAN_COLOURS['TRG'], 0.35)
    for ob in COLL['Stormshrine_Markers'].objects:
        key = ob.name[len(ASSET_PREFIX):].split('_')[0]
        if ob.type == 'MESH':
            ob.hide_render = False
            ob.data.materials[0] = trg
            made.append(('restore', ob))
        elif key in PLAN_COLOURS and abs(ob.location.x) < 16 and abs(ob.location.y + 4) < 14 and ob.location.z < 8:
            mb = MB()
            lathe(mb, [(0.0, 0.0), (0.32, 0.0), (0.32, 0.04), (0.0, 0.04)], 20, 'PLAN_' + key)
            if 'PLAN_' + key not in MATS:
                MATS['PLAN_' + key] = glow_mat('PLAN_' + key, PLAN_COLOURS[key], 0.9)
            mb.transform(translate(ob.location.x, ob.location.y, ob.location.z + 0.06))
            disc = mb_to_object(mb, 'PLAN_' + ob.name, COLL['Preview_Rig'])
            ASSET_OBJECTS.remove(disc)
            made.append(('delete', disc))
    sun = add_light(COLL['Preview_Rig'], 'PLAN_TopLight', 'SUN', (0, 0, 50), (0, 0, 0), 1.2, '#ffffff', 10.0)
    made.append(('delete', sun))
    return made


def render_views(views, cams, out_dir, debug_normals=False):
    sc = bpy.context.scene
    os.makedirs(out_dir, exist_ok=True)
    ref = COLL.get('REF_PlayerScale')
    names = dict(front='Stormshrine_Front', side='Stormshrine_Side', threequarter='Stormshrine_ThreeQuarter',
                 threequarter_back='Stormshrine_ThreeQuarter_Back', playerscale='Stormshrine_PlayerScale',
                 detail='Stormshrine_Detail_Altar', plan='Stormshrine_Plan')
    for v in views:
        if ref:
            ref.hide_render = v != 'playerscale'
        overlay = plan_overlay() if v == 'plan' else []
        sc.camera = cams[v]
        sc.render.filepath = os.path.join(out_dir, names[v] + '.png')
        t0 = time.time()
        bpy.ops.render.render(write_still=True)
        print('  rendered %-14s %.0fs' % (v, time.time() - t0))
        for what, ob in overlay:     # the overlay is never saved; undo it for any later views
            if what == 'restore':
                ob.hide_render = True
                ob.data.materials[0] = MATS[ASSET_PREFIX + 'TriggerVolume']
            else:
                bpy.data.objects.remove(ob)
    if ref:
        ref.hide_render = True
    if debug_normals:
        mat = bpy.data.materials.new('DEBUG_Backfacing')
        nt = node_tree(mat)
        nt.nodes.clear()
        geo = nt.nodes.new('ShaderNodeNewGeometry')
        mix = nt.nodes.new('ShaderNodeMix')
        mix.data_type = 'RGBA'
        em = nt.nodes.new('ShaderNodeEmission')
        out = nt.nodes.new('ShaderNodeOutputMaterial')
        mix_socket(mix, 'A').default_value = (0.1, 0.3, 1.0, 1)
        mix_socket(mix, 'B').default_value = (1.0, 0.0, 0.0, 1)
        nt.links.new(geo.outputs['Backfacing'], mix_socket(mix, 'Factor', 'VALUE'))
        nt.links.new(mix_socket(mix, 'Result', out=True), em.inputs['Color'])
        nt.links.new(em.outputs['Emission'], out.inputs['Surface'])
        vl = bpy.context.view_layer
        vl.material_override = mat
        old = sc.cycles.samples
        sc.cycles.samples = 4
        for v in ('front', 'threequarter', 'side', 'detail'):
            sc.camera = cams[v]
            sc.render.filepath = os.path.join(out_dir, 'DEBUG_normals_%s.png' % v)
            bpy.ops.render.render(write_still=True)
        vl.material_override = None
        sc.cycles.samples = old


