def lathe(mb, profile, segs, mats, smooth=True, closed=False, theta0=0.0):
    """Surface of revolution about +Z. profile: [(r, z)], walked with the solid
    on the left (outer surfaces bottom-to-top). mats: name or per-segment list."""
    isl = mb.island()
    n = len(profile)
    rings = []
    for r, z in profile:
        if r < 1e-7:
            rings.append([mb.vert((0.0, 0.0, z))])
        else:
            rings.append([mb.vert((r * math.cos(theta0 + 2 * math.pi * j / segs),
                                   r * math.sin(theta0 + 2 * math.pi * j / segs), z)) for j in range(segs)])
    vs = [0.0]
    pairs = [(i, i + 1) for i in range(n - 1)] + ([(n - 1, 0)] if closed else [])
    for a, b in pairs:
        vs.append(vs[-1] + math.dist(profile[a], profile[b]))
    for k, (a, b) in enumerate(pairs):
        m = mats if isinstance(mats, str) else mats[k]
        A, B = rings[a], rings[b]
        ra, rb = profile[a][0], profile[b][0]
        va, vb = vs[k], vs[k + 1]
        if len(A) == 1 and len(B) == 1:
            continue
        for j in range(segs):
            j1 = (j + 1) % segs
            u = lambda r, jj: (jj / segs - 0.5) * 2 * math.pi * r
            if len(A) == 1:
                mb.face([A[0], B[j1], B[j]], [(0.0, va), (u(rb, j + 1), vb), (u(rb, j), vb)], m, smooth, isl)
            elif len(B) == 1:
                mb.face([A[j], A[j1], B[0]], [(u(ra, j), va), (u(ra, j + 1), va), (0.0, vb)], m, smooth, isl)
            else:
                mb.face([A[j], A[j1], B[j1], B[j]],
                        [(u(ra, j), va), (u(ra, j + 1), va), (u(rb, j + 1), vb), (u(rb, j), vb)], m, smooth, isl)
    return mb


def transport_frames(path, ref):
    n = len(path)
    T = []
    for i in range(n):
        if i == 0:
            t = path[1] - path[0]
        elif i == n - 1:
            t = path[-1] - path[-2]
        else:
            t = (path[i + 1] - path[i]).normalized() + (path[i] - path[i - 1]).normalized()
        T.append(t.normalized())
    r = ref - ref.dot(T[0]) * T[0]
    if r.length < 1e-6:
        r = Vector((0, 1, 0)) - Vector((0, 1, 0)).dot(T[0]) * T[0]
    N = [r.normalized()]
    for i in range(1, n):
        q = T[i - 1].rotation_difference(T[i])
        nn = q @ N[-1]
        N.append((nn - nn.dot(T[i]) * T[i]).normalized())
    B = [T[i].cross(N[i]) for i in range(n)]
    return T, N, B


def circle(n, phase=0.0):
    return [(math.cos(phase + 2 * math.pi * k / n), math.sin(phase + 2 * math.pi * k / n)) for k in range(n)]


def sweep(mb, path, radii, section, mats, smooth=True, cap_start=False, cap_end=False,
          ref=Vector((0, 0, 1)), cap_mat=None, radial_fn=None):
    """Sweep a closed CCW cross-section along a path (parallel-transport frames).
    section: [(x, y)] in the ring plane (x along N, y along B = T x N).
    mats: name or per-section-edge list. A radius <= 1e-6 collapses to a tip.
    radial_fn(i, k) optionally scales section point k of ring i (bark noise)."""
    path = [Vector(p) for p in path]
    _, N, B = transport_frames(path, ref)
    ns = len(section)
    isl = mb.island()
    rings = []
    for i, (p, r) in enumerate(zip(path, radii)):
        if r <= 1e-6:
            rings.append([mb.vert(p)])
            continue
        ring = []
        for k, (x, y) in enumerate(section):
            s = r * (radial_fn(i, k) if radial_fn else 1.0)
            ring.append(mb.vert(p + N[i] * (x * s) + B[i] * (y * s)))
        rings.append(ring)
    # u: arc length around the section at each ring's radius (centred), v: path length
    per = [math.dist(section[k], section[(k + 1) % ns]) for k in range(ns)]
    cum = [0.0]
    for d in per:
        cum.append(cum[-1] + d)
    P = cum[-1]
    vlen = [0.0]
    for i in range(1, len(path)):
        vlen.append(vlen[-1] + (path[i] - path[i - 1]).length)
    for i in range(len(path) - 1):
        A, Bv = rings[i], rings[i + 1]
        ra, rb = radii[i], radii[i + 1]
        for k in range(ns):
            k1 = (k + 1) % ns
            m = mats if isinstance(mats, str) else mats[k]
            ua0, ua1 = (cum[k] - P / 2) * ra, (cum[k + 1] - P / 2) * ra
            ub0, ub1 = (cum[k] - P / 2) * rb, (cum[k + 1] - P / 2) * rb
            if len(Bv) == 1:
                mb.face([A[k], A[k1], Bv[0]], [(ua0, vlen[i]), (ua1, vlen[i]), ((ua0 + ua1) / 2, vlen[i + 1])],
                        m, smooth, isl)
            elif len(A) == 1:
                mb.face([A[0], Bv[k1], Bv[k]], [((ub0 + ub1) / 2, vlen[i]), (ub1, vlen[i + 1]), (ub0, vlen[i + 1])],
                        m, smooth, isl)
            else:
                mb.face([A[k], A[k1], Bv[k1], Bv[k]],
                        [(ua0, vlen[i]), (ua1, vlen[i]), (ub1, vlen[i + 1]), (ub0, vlen[i + 1])], m, smooth, isl)
    cm = cap_mat or (mats if isinstance(mats, str) else mats[0])
    for which, do in ((0, cap_start), (-1, cap_end)):
        ring = rings[which]
        if not do or len(ring) == 1:
            continue
        ci = mb.island()
        r = radii[which]
        uvs = [(x * r, y * r) for x, y in section]
        ids = list(ring)
        if which == 0:
            ids, uvs = ids[::-1], uvs[::-1]
        mb.face(ids, uvs, cm, False, ci)
    return rings


def extrude_shape(mb, outline, thickness, mat_face, mat_side, smooth_side=False):
    """Flat shape in the local X-Z plane (CCW seen from -Y), extruded along Y
    from -t/2 (front) to +t/2 (back)."""
    outline = ccw(outline)
    n = len(outline)
    h = thickness / 2
    fr = [mb.vert((x, -h, z)) for x, z in outline]
    bk = [mb.vert((x, h, z)) for x, z in outline]
    tris = mgeo.tessellate_polygon([[Vector((x, z, 0)) for x, z in outline]])
    fi, bi = mb.island(), mb.island()
    for t in tris:
        t = list(t)
        if signed_area([outline[k] for k in t]) < 0:
            t.reverse()
        mb.face([fr[k] for k in t], [outline[k] for k in t], mat_face, False, fi)
        tb = t[::-1]
        mb.face([bk[k] for k in tb], [(-outline[k][0], outline[k][1]) for k in tb], mat_face, False, bi)
    si = mb.island()
    acc = 0.0
    for k in range(n):
        k1 = (k + 1) % n
        d = math.dist(outline[k], outline[k1])
        mb.face([fr[k], bk[k], bk[k1], fr[k1]], [(acc, 0), (acc, thickness), (acc + d, thickness), (acc + d, 0)],
                mat_side, smooth_side, si)
        acc += d
    return mb


def plane_map(origin, e1, e2):
    """Surface map for a plane: (s, t, h) -> origin + s*e1 + t*e2 + h*(e1 x e2)."""
    o, a, b = Vector(origin), Vector(e1), Vector(e2)
    n = a.cross(b)
    return lambda s, t, h: o + a * s + b * t + n * h


def revolution_map(centre, rfun, theta0, r_ref, z_axis=True):
    """Surface map for a surface of revolution about +Z through centre:
    (s, t, h) -> point at angle theta0 + s/r_ref, height t, radius rfun(t) + h."""
    cx, cy, cz = centre

    def f(s, t, h):
        th = theta0 + s / r_ref
        r = rfun(t) + h
        return Vector((cx + r * math.cos(th), cy + r * math.sin(th), cz + t))
    return f


def relief_stroke(mb, pts, width, height, fmap, mat, embed=0.004, closed=False, samples=1):
    """Raised stroke along 2-D pts (metric surface coords) on a mapped surface.
    Open back (no bottom): the walls dip `embed` below the surface."""
    P = [Vector(p) for p in pts]
    if samples > 1:   # subdivide straight segments so the stroke follows curved surfaces
        Q = []
        rng = range(len(P)) if closed else range(len(P) - 1)
        for i in rng:
            a, b = P[i], P[(i + 1) % len(P)]
            for k in range(samples):
                Q.append(a.lerp(b, k / samples))
        if not closed:
            Q.append(P[-1])
        P = Q
    n = len(P)
    L, R = [], []
    for i in range(n):
        if closed or 0 < i < n - 1:
            d0 = (P[i] - P[i - 1]).normalized()
            d1 = (P[(i + 1) % n] - P[i]).normalized()
            n0, n1 = Vector((-d0.y, d0.x)), Vector((-d1.y, d1.x))
            m = n0 + n1
            m = n0 if m.length < 1e-6 else m.normalized()
            k = 1.0 / max(m.dot(n0), 0.4)
        else:
            d = (P[1] - P[0]).normalized() if i == 0 else (P[-1] - P[-2]).normalized()
            m, k = Vector((-d.y, d.x)), 1.0
        L.append(P[i] + m * (width / 2 * k))
        R.append(P[i] - m * (width / 2 * k))
    Lt = [mb.vert(fmap(p.x, p.y, height)) for p in L]
    Rt = [mb.vert(fmap(p.x, p.y, height)) for p in R]
    Lb = [mb.vert(fmap(p.x, p.y, -embed)) for p in L]
    Rb = [mb.vert(fmap(p.x, p.y, -embed)) for p in R]
    acc = [0.0]
    for i in range(1, n + (1 if closed else 0)):
        acc.append(acc[-1] + (P[i % n] - P[i - 1]).length)
    top, ls, rs = mb.island(), mb.island(), mb.island()
    hh = height + embed
    segs = range(n) if closed else range(n - 1)
    for i in segs:
        j = (i + 1) % n
        u0, u1 = acc[i], acc[i + 1]
        mb.face([Lt[i], Rt[i], Rt[j], Lt[j]], [(u0, width), (u0, 0), (u1, 0), (u1, width)], mat, False, top)
        mb.face([Lb[i], Lt[i], Lt[j], Lb[j]], [(u0, 0), (u0, hh), (u1, hh), (u1, 0)], mat, False, ls)
        mb.face([Rb[i], Rb[j], Rt[j], Rt[i]], [(u0, 0), (u1, 0), (u1, hh), (u0, hh)], mat, False, rs)
    if not closed:
        c0, c1 = mb.island(), mb.island()
        mb.face([Lb[0], Rb[0], Rt[0], Lt[0]], [(0, 0), (width, 0), (width, hh), (0, hh)], mat, False, c0)
        e = n - 1
        mb.face([Lb[e], Lt[e], Rt[e], Rb[e]], [(0, 0), (0, hh), (width, hh), (width, 0)], mat, False, c1)
    return mb


def relief_fill(mb, outline, height, fmap, mat, embed=0.004):
    """Raised filled shape (CCW outline in surface coords), open back."""
    outline = ccw(outline)
    n = len(outline)
    top = [mb.vert(fmap(x, y, height)) for x, y in outline]
    bot = [mb.vert(fmap(x, y, -embed)) for x, y in outline]
    ti = mb.island()
    if n <= 12 and all(signed_area([outline[k - 1], outline[k], outline[(k + 1) % n]]) > 0 for k in range(n)):
        mb.face(top, outline, mat, False, ti)
    else:
        for t in mgeo.tessellate_polygon([[Vector((x, y, 0)) for x, y in outline]]):
            t = list(t)
            if signed_area([outline[k] for k in t]) < 0:
                t.reverse()
            mb.face([top[k] for k in t], [outline[k] for k in t], mat, False, ti)
    si = mb.island()
    acc = 0.0
    hh = height + embed
    for k in range(n):
        k1 = (k + 1) % n
        d = math.dist(outline[k], outline[k1])
        mb.face([bot[k], bot[k1], top[k1], top[k]], [(acc, 0), (acc + d, 0), (acc + d, hh), (acc, hh)], mat, False, si)
        acc += d
    return mb


def ellipse(cx, cy, rx, ry, n=14, rot=0.0):
    c, s = math.cos(rot), math.sin(rot)
    return [(cx + rx * math.cos(a) * c - ry * math.sin(a) * s, cy + rx * math.cos(a) * s + ry * math.sin(a) * c)
            for a in (2 * math.pi * k / n for k in range(n))]


def box_mb(mb, x0, x1, y0, y1, z0, z1, mat, skip=()):
    """Axis-aligned box; skip: subset of {'bottom','top','front','back','left','right'}."""
    c = [(x0, y0, z0), (x1, y0, z0), (x1, y1, z0), (x0, y1, z0), (x0, y0, z1), (x1, y0, z1), (x1, y1, z1), (x0, y1, z1)]
    vid = [mb.vert(p) for p in c]
    faces = dict(bottom=(0, 3, 2, 1), top=(4, 5, 6, 7), front=(0, 1, 5, 4), right=(1, 2, 6, 5),
                 back=(2, 3, 7, 6), left=(3, 0, 4, 7))
    for name, f in faces.items():
        if name in skip:
            continue
        pts = [c[i] for i in f]
        nrm = (Vector(pts[1]) - Vector(pts[0])).cross(Vector(pts[3]) - Vector(pts[0])).normalized()
        ax = max(range(3), key=lambda a: abs(nrm[a]))
        uvs = [(p[(ax + 1) % 3], p[(ax + 2) % 3]) for p in pts]
        mb.face([vid[i] for i in f], uvs, mat, False, mb.island())
    return mb


def rrect(hx, hy, r, nx, ny, na):
    """Rounded rectangle, CCW from above, starting at the left end of the front
    (y = -hy) straight. Fixed point count 2*(nx+ny) + 4*na for any size."""
    pts = []
    sides = [((-(hx - r), -hy), (hx - r, -hy), nx, (hx - r, -(hy - r)), -math.pi / 2),
             ((hx, -(hy - r)), (hx, hy - r), ny, (hx - r, hy - r), 0.0),
             ((hx - r, hy), (-(hx - r), hy), nx, (-(hx - r), hy - r), math.pi / 2),
             ((-hx, hy - r), (-hx, -(hy - r)), ny, (-(hx - r), -(hy - r)), math.pi)]
    for (a, b, nseg, cc, a0) in sides:
        for k in range(nseg):
            t = k / nseg
            pts.append((a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t))
        for k in range(na):
            ang = a0 + (math.pi / 2) * k / na
            pts.append((cc[0] + r * math.cos(ang), cc[1] + r * math.sin(ang)))
    return pts


