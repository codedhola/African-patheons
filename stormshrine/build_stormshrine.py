MATS = {}


def node_tree(idblock):
    """Node tree of a material or world. Blender 5 always uses nodes and
    deprecates use_nodes (removal planned for 6.0); 4.x still needs it set."""
    if idblock.node_tree is None or bpy.app.version < (5, 0, 0):
        idblock.use_nodes = True
    return idblock.node_tree


def _img(path, colorspace):
    img = bpy.data.images.load(path, check_existing=True)
    img.colorspace_settings.name = colorspace
    return img


def make_material(name, base, rough=0.8, normal=None, tile=1.0, metallic=0.0, emission=None,
                  emission_strength=0.0, normal_strength=1.0, ior=1.5, sheen=0.0, coat=0.0,
                  spec=0.5, viewport=None):
    """Principled PBR material. base/emission: hex colour or image path;
    rough: float or image path; normal: image path or None."""
    mat = bpy.data.materials.new(name)
    nt = node_tree(mat)
    nt.nodes.clear()
    out = nt.nodes.new('ShaderNodeOutputMaterial')
    out.location = (400, 0)
    bsdf = nt.nodes.new('ShaderNodeBsdfPrincipled')
    bsdf.location = (100, 0)
    nt.links.new(bsdf.outputs['BSDF'], out.inputs['Surface'])
    vec = None
    if any(isinstance(x, str) and x.endswith('.png') for x in (base, rough, normal, emission)):
        tc = nt.nodes.new('ShaderNodeTexCoord')
        tc.location = (-900, 0)
        mp = nt.nodes.new('ShaderNodeMapping')
        mp.location = (-720, 0)
        tu, tv = tile if isinstance(tile, tuple) else (tile, tile)
        mp.inputs['Scale'].default_value = (1.0 / tu, 1.0 / tv, 1.0)
        nt.links.new(tc.outputs['UV'], mp.inputs['Vector'])
        vec = mp.outputs['Vector']

    def tex(path, cs, y):
        node = nt.nodes.new('ShaderNodeTexImage')
        node.image = _img(path, cs)
        node.location = (-450, y)
        nt.links.new(vec, node.inputs['Vector'])
        return node

    if isinstance(base, str) and base.endswith('.png'):
        nt.links.new(tex(base, 'sRGB', 300).outputs['Color'], bsdf.inputs['Base Color'])
        vp = viewport or (0.3, 0.2, 0.15)
    else:
        col = lin(base)
        bsdf.inputs['Base Color'].default_value = (*col, 1.0)
        vp = viewport or col
    if isinstance(rough, str):
        nt.links.new(tex(rough, 'Non-Color', 0).outputs['Color'], bsdf.inputs['Roughness'])
    else:
        bsdf.inputs['Roughness'].default_value = rough
    bsdf.inputs['Metallic'].default_value = metallic
    bsdf.inputs['IOR'].default_value = ior
    bsdf.inputs['Specular IOR Level'].default_value = spec
    if sheen:
        bsdf.inputs['Sheen Weight'].default_value = sheen
    if coat:
        bsdf.inputs['Coat Weight'].default_value = coat
    if normal:
        nm = nt.nodes.new('ShaderNodeNormalMap')
        nm.location = (-180, -300)
        nm.uv_map = 'UVMap'
        nm.inputs['Strength'].default_value = normal_strength
        nt.links.new(tex(normal, 'Non-Color', -300).outputs['Color'], nm.inputs['Color'])
        nt.links.new(nm.outputs['Normal'], bsdf.inputs['Normal'])
    if emission is not None:
        if isinstance(emission, str) and emission.endswith('.png'):
            nt.links.new(tex(emission, 'sRGB', -600).outputs['Color'], bsdf.inputs['Emission Color'])
        else:
            bsdf.inputs['Emission Color'].default_value = (*lin(emission), 1.0)
        bsdf.inputs['Emission Strength'].default_value = emission_strength
    mat.diffuse_color = (*vp[:3], 1.0)
    mat.roughness = rough if isinstance(rough, float) else 0.7
    MATS[name] = mat
    return mat


