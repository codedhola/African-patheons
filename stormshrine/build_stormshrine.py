def build_hilltop(coll):
    """Stormshrine_Hilltop: flat wet crown (z = 0) falling away to a rough crest."""
    mb = MB()
    cx, cy = HILL_CENTRE
    rings = [0.0, 1.5, 3, 4.5, 6, 7.5, 9, 10.5, 12, 13.5, 15, 16.0, 17.0, 18.0, 19.0, 20.5, 22.0, 23.5, 25.0, 27.0,
             29.0]
    segs = 72
    rnd = random.Random(11)
    ph = [rnd.uniform(0, 2 * math.pi) for _ in range(4)]
    shape = lambda a: 1.0 + 0.06 * math.sin(3 * a + ph[0]) + 0.04 * math.sin(5 * a + ph[1]) + 0.025 * math.sin(9 * a + ph[2])
    FLAT, EDGE, DROP = 15.0, 29.0, 7.0

    def height(r, a):
        if r <= FLAT:
            return 0.0
        k = (r - FLAT) / (EDGE - FLAT)
        return -DROP * k ** 1.6 + 0.35 * k * math.sin(7 * a + ph[3] + r * 0.7) + 0.25 * k * math.sin(13 * a + r * 1.3)
    vid = []
    for r in rings:
        if r == 0:
            vid.append([mb.vert((cx, cy, 0.0))])
            continue
        row = []
        for j in range(segs):
            a = 2 * math.pi * j / segs
            f = shape(a) if r > 9 else 1.0 + (shape(a) - 1.0) * r / 9.0
            row.append(mb.vert((cx + r * f * math.cos(a), cy + r * f * math.sin(a), height(r, a))))
        vid.append(row)
    isl = mb.island()
    uv = lambda i: (mb.v[i].x, mb.v[i].y)
    for i in range(len(rings) - 1):
        A, B = vid[i], vid[i + 1]
        for j in range(segs):
            j1 = (j + 1) % segs
            if len(A) == 1:
                f = [A[0], B[j], B[j1]]
            else:
                f = [A[j], B[j], B[j1], A[j1]]
            mb.face(f, [uv(k) for k in f], ASSET_PREFIX + 'Ground_Wet', True, isl)
    return mb_to_object(mb, ASSET_PREFIX + 'Hilltop', coll, sharp_angle=60)


def build_scar(coll):
    """Stormshrine_LightningScar: the glowing crack in the wet ground
    (SVG 690,712 ... 920,722 plus the branch to 812,750): emissive core between
    torn earth lips. Core UV v runs 0..1 across the crack."""
    mb = MB()
    ground, glow = ASSET_PREFIX + 'Ground_Wet', ASSET_PREFIX + 'LightningScar'
    rnd = random.Random(3)
    to3 = lambda x, y: (Vector(((x - 805) * 0.030, -8.2 - (y - 720) * 0.05)))
    main = [to3(*p) for p in ((690, 712), (730, 722), (756, 708), (800, 728), (832, 714), (870, 732), (920, 722))]
    branch = [to3(*p) for p in ((800, 728), (812, 750))]
    branch[0] = branch[0] + (branch[1] - branch[0]) * 0.08

    def resample(poly, step=0.12):
        out = [poly[0]]
        for a, b in zip(poly, poly[1:]):
            n = max(1, int((b - a).length / step))
            for k in range(1, n + 1):
                p = a.lerp(b, k / n)
                if k < n:
                    d = (b - a).normalized()
                    p = p + Vector((-d.y, d.x)) * rnd.uniform(-0.035, 0.035)
                out.append(p)
        return out

    def crack(poly, wmax):
        P = resample(poly)
        n = len(P)
        acc = [0.0]
        for i in range(1, n):
            acc.append(acc[-1] + (P[i] - P[i - 1]).length)
        tot = acc[-1]
        prof = []   # per point: (offset, z) across, left to right
        for i in range(n):
            t = acc[i] / tot
            env = math.sin(math.pi * min(max(t, 0.0), 1.0)) ** 0.6
            core = wmax * env * rnd.uniform(0.75, 1.15) + 0.004
            lipw = core / 2 + 0.03 + 0.16 * env * rnd.uniform(0.7, 1.1)
            lz = 0.004 + 0.035 * env * rnd.uniform(0.7, 1.2)
            prof.append([(-lipw - 0.06, 0.0), (-core / 2 - 0.02, lz), (-core / 2, 0.008), (core / 2, 0.008),
                         (core / 2 + 0.02, lz), (lipw + 0.06, 0.0)])
        rows = []
        for i in range(n):
            if 0 < i < n - 1:
                d = ((P[i + 1] - P[i]).normalized() + (P[i] - P[i - 1]).normalized()).normalized()
            else:
                d = (P[1] - P[0]).normalized() if i == 0 else (P[-1] - P[-2]).normalized()
            nrm = Vector((-d.y, d.x))
            rows.append([mb.vert((P[i].x + nrm.x * -o, P[i].y + nrm.y * -o, z)) for o, z in prof[i]])
        lipL, lipR, core_i = mb.island(), mb.island(), mb.island()
        for i in range(n - 1):
            A, B = rows[i], rows[i + 1]
            for c in range(5):
                q = [A[c], A[c + 1], B[c + 1], B[c]]
                if c == 2:
                    uvs = [(acc[i], 0), (acc[i], 1), (acc[i + 1], 1), (acc[i + 1], 0)]
                    mb.face(q, uvs, glow, False, core_i)
                else:
                    uvs = [(prof[i][c][0], acc[i]), (prof[i][c + 1][0], acc[i]),
                           (prof[i + 1][c + 1][0], acc[i + 1]), (prof[i + 1][c][0], acc[i + 1])]
                    mb.face(q, uvs, ground, True, lipL if c < 2 else lipR)
    crack(main, 0.16)
    crack(branch, 0.08)
    # the core's v must stay 0..1 across the crack: move islands by whole tiles only
    return mb_to_object(mb, ASSET_PREFIX + 'LightningScar', coll, snap=(2.0, 1.0))


def build_puddles(coll):
    """Stormshrine_Puddles: rain pools (SVG ellipses at x 420, 1180, 760).
    A very flat lens: the centre sits 4 mm above the ground, the rim 4 mm below,
    so the visible outline is where it crosses the ground (no floating edge)."""
    mb = MB()
    rnd = random.Random(5)
    for (x, y, rx, ry, rot) in ((-5.2, -11.4, 2.4, 1.15, 0.12), (4.7, -12.4, 2.8, 1.3, -0.08),
                                (-0.5, -14.2, 3.0, 1.2, 0.04)):
        isl = mb.island()
        n = 28
        jit = [1 + 0.12 * math.sin(3 * a + rnd.uniform(0, 6)) + 0.06 * math.sin(7 * a + rnd.uniform(0, 6))
               for a in (2 * math.pi * k / n for k in range(n))]
        ring = lambda s, z: [mb.vert((x + (rx * s * jit[k] * math.cos(a)) * math.cos(rot) - (ry * s * jit[k] * math.sin(a)) * math.sin(rot),
                                      y + (rx * s * jit[k] * math.cos(a)) * math.sin(rot) + (ry * s * jit[k] * math.sin(a)) * math.cos(rot),
                                      z)) for k, a in enumerate(2 * math.pi * k / n for k in range(n))]
        cen = mb.vert((x, y, 0.004))
        inner, outer = ring(0.75, 0.004), ring(1.0, -0.004)
        uv = lambda i: (mb.v[i].x, mb.v[i].y)
        W = ASSET_PREFIX + 'Puddle_Water'
        for k in range(n):
            k1 = (k + 1) % n
            mb.face([cen, inner[k], inner[k1]], [uv(cen), uv(inner[k]), uv(inner[k1])], W, False, isl)
            mb.face([inner[k], outer[k], outer[k1], inner[k1]], [uv(inner[k]), uv(outer[k]), uv(outer[k1]), uv(inner[k1])],
                    W, False, isl)
    return mb_to_object(mb, ASSET_PREFIX + 'Puddles', coll)


def build_rocks(coll):
    """Stormshrine_Rocks: dark stones on the hilltop (SVG pebble ellipses)."""
    bm = bmesh.new()
    rnd = random.Random(13)
    spots = [(-5.6, -7.6, 0.32), (-2.9, -12.6, 0.22), (5.9, -8.4, 0.36), (2.4, -15.3, 0.26), (-9.4, -5.8, 0.42),
             (9.0, -5.2, 0.34), (-4.4, -2.2, 0.18), (6.2, -1.0, 0.24), (-1.2, -9.8, 0.14)]
    for x, y, r in spots:
        res = bmesh.ops.create_icosphere(bm, subdivisions=2, radius=1.0)
        ph = [rnd.uniform(0, 6.28) for _ in range(3)]
        for v in res['verts']:
            d = v.co.normalized()
            k = 1 + 0.18 * math.sin(3 * d.x + ph[0]) * math.cos(2 * d.y + ph[1]) + 0.1 * math.sin(5 * d.z + ph[2])
            v.co = Vector((d.x * k * r * 1.2, d.y * k * r, d.z * k * r * 0.7))
        bmesh.ops.transform(bm, matrix=translate(x, y, r * 0.18) @ rot_z(rnd.uniform(0, 6.28)), verts=res['verts'])
    for f in bm.faces:
        f.smooth = True
    return bm_to_object(bm, ASSET_PREFIX + 'Rocks', coll, ASSET_PREFIX + 'Rock')


