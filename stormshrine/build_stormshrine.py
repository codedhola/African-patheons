def build_thunderstones(coll):
    """Stormshrine_Thunderstones: edun ara, polished stone celts heaped in the bowl."""
    bm = bmesh.new()
    rnd = random.Random(7)
    cx, cy = ALTAR_POS
    stones = [((-0.09, 0.03, 1.31), 0.19, 0.4), ((0.08, -0.05, 1.315), 0.17, 2.1), ((0.0, 0.10, 1.305), 0.18, 1.2),
              ((0.05, 0.06, 1.345), 0.15, 2.8), ((-0.06, -0.08, 1.325), 0.16, 0.9), ((0.0, -0.005, 1.37), 0.14, 1.7)]
    for (x, y, z), L, yaw in stones:
        res = bmesh.ops.create_uvsphere(bm, u_segments=10, v_segments=6, radius=1.0)
        vs = res['verts']
        W, Th = L * 0.46, L * 0.24
        for v in vs:
            a = v.co.x
            taper = 0.72 + 0.28 * (a + 1) / 2
            edge = 1.0 - max(0.0, a - 0.55) * 1.4
            v.co = Vector((a * L / 2, v.co.y * W / 2 * taper, v.co.z * Th / 2 * (0.8 + 0.2 * (a + 1) / 2) * edge))
        M = translate(cx + x, cy + y, z) @ rot_z(yaw) @ Matrix.Rotation(rnd.uniform(-0.35, 0.35), 4, 'X') \
            @ Matrix.Rotation(rnd.uniform(-0.25, 0.25), 4, 'Y')
        bmesh.ops.transform(bm, matrix=M, verts=vs)
    for f in bm.faces:
        f.smooth = True
    return bm_to_object(bm, ASSET_PREFIX + 'Thunderstones', coll, ASSET_PREFIX + 'Thunderstone')


def ose_blade_outline():
    """Oṣé blade from the staff heads (SVG M650 530 C630 520 626 500 636 488 ...),
    made symmetric; base point at (0, 0), metres."""
    k = 0.019
    left_outer = ((0, 0), (-21, 9), (-27, 27), (-19, 40))
    left_inner = ((-19, 40), (-10, 30), (-3, 20), (0, 4))
    mirror = lambda seg: tuple((-x, y) for x, y in reversed(seg))
    pts = bez_path([left_outer, left_inner, mirror(left_inner), mirror(left_outer)], 8)[:-1]
    return [(x * k, y * k) for x, y in pts]


def build_staff(coll, name, bottom, top, blade_mat):
    """Oṣé staff leaning on the front wall: pole, knob and a flat double blade
    held parallel to the wall."""
    mb = MB()
    wood = ASSET_PREFIX + 'Wood_Dark'
    b, t = Vector(bottom), Vector(top)
    D = (t - b).normalized()
    sweep(mb, [b + D * (-0.03), b.lerp(t, 0.5), t], [0.034, 0.032, 0.028], circle(10), wood,
          cap_start=True, cap_end=True, ref=Vector((1, 0, 0)))
    knob = MB()
    lathe(knob, [(0.0, -0.055), (0.035, -0.045), (0.055, -0.01), (0.05, 0.03), (0.03, 0.055), (0.0, 0.062)], 12, wood)
    knob.transform(translate(*t) @ D.to_track_quat('Z', 'Y').to_matrix().to_4x4())
    mb.merge(knob)
    blade = MB()
    extrude_shape(blade, ose_blade_outline(), 0.035, blade_mat, blade_mat)
    U = Vector((D.x, 0.0, D.z)).normalized()
    Y = Vector((0, 1, 0))
    S = Y.cross(U)
    R = Matrix((S, Y, U)).transposed().to_4x4()
    blade.transform(translate(*(t + U * 0.015)) @ R)
    mb.merge(blade)
    return mb_to_object(mb, name, coll)


def drum_mb(L, rs, rl, n_lace, n_beads):
    """A bàtá drum built along +Z (small head at z=0). Conical body with a waist
    near the small head, rawhide heads and hoops, zigzag thongs and a band of
    red and white beads (SVG 846..924, y 648..684)."""
    mb = MB()
    wood, hide = ASSET_PREFIX + 'Wood_Carved', ASSET_PREFIX + 'Hide'
    flare = [(0.45, 0.30), (0.70, 0.72), (0.88, 0.93), (1.0, 1.0)]   # (along, share of rs->rl)
    body = [(rs, 0.0), (rs * 0.985, 0.07 * L), (rs * 0.94, 0.22 * L)] + [(rs + (rl - rs) * t, a * L)
                                                                         for a, t in flare]
    lathe(mb, body, 22, wood)
    rfun = lambda z: interp([(z_, r_) for r_, z_ in body], z)
    # heads: small faces -Z, large faces +Z
    lathe(mb, [(0.0, -0.006), (rs * 0.6, -0.006), (rs + 0.002, -0.006)], 22, hide)
    lathe(mb, [(rl + 0.002, L + 0.006), (rl * 0.6, L + 0.006), (0.0, L + 0.006)], 22, hide)
    # hoops (closed rings, CCW in r-z)
    for r0, z0, z1, w in ((rs, -0.014, 0.026, 0.014), (rl, L - 0.03, L + 0.014, 0.016)):
        lathe(mb, [(r0 - 0.006, z0), (r0 + w, z0), (r0 + w, z1), (r0 - 0.006, z1)], 22, hide, closed=True)
    # zigzag thongs (separate straps so the joins hide under the hoops)
    r_ref = rfun(0.5 * L)
    fm = revolution_map((0, 0, 0), rfun, 0.0, r_ref)
    za, zb = 0.012, L - 0.016
    step = 2 * math.pi * r_ref / n_lace
    for i in range(n_lace):
        s0 = i * step
        # alternate the thong heights so the ends that cross under the hoops never share a surface
        for (a, b_), h in ((((s0, za), (s0 + step / 2, zb)), 0.004), (((s0 + step / 2, zb), (s0 + step, za)), 0.006)):
            relief_stroke(mb, [a, b_], 0.013, h, fm, hide, embed=0.003, samples=6)
    # bead band
    zb_ = 0.48 * L
    for i in range(n_beads):
        th = 2 * math.pi * (i + 0.5) / n_beads
        r = rfun(zb_) + 0.006
        bead = MB()
        rr = 0.012
        lathe(bead, [(0.0, -rr)] + [(rr * math.sin(math.pi * k / 4), -rr * math.cos(math.pi * k / 4))
                                    for k in (1, 2, 3)] + [(0.0, rr)], 6,
              ASSET_PREFIX + ('Beads_Red' if i % 2 == 0 else 'Beads_White'))
        bead.transform(translate(r * math.cos(th), r * math.sin(th), zb_))
        mb.merge(bead)
    return mb


def place_drum(mb, L, rs, rl, pos, yaw):
    """Lay a drum (built along +Z) on the ground with its axis along +X before yaw."""
    mb.transform(Matrix.Rotation(math.pi / 2, 4, 'Y'))          # +Z -> +X
    tilt = math.atan(((rl + 0.016) - (rs + 0.014)) / L)
    mb.transform(Matrix.Rotation(-tilt, 4, 'Y'))                  # lift the large end: level bottom line
    zmin = min(v.z for v in mb.v)
    mb.transform(translate(*pos, 0.0015 - zmin) @ rot_z(yaw))
    return mb


def build_drums(coll):
    big = drum_mb(0.85, 0.10, 0.17, 10, 16)
