def write_png(path, arr):
    """arr: HxW or HxWx3 uint8 with row 0 = bottom (v = 0). Adaptive filtering."""
    a = np.ascontiguousarray(np.flipud(arr))
    h, w = a.shape[:2]
    ch = 1 if a.ndim == 2 else a.shape[2]
    rows = a.reshape(h, w * ch).astype(np.int16)
    left = np.concatenate([np.zeros((h, ch), np.int16), rows[:, :-ch]], 1)
    up = np.concatenate([np.zeros((1, w * ch), np.int16), rows[:-1]], 0)
    upleft = np.concatenate([np.zeros((1, w * ch), np.int16), left[:-1]], 0)
    p = left + up - upleft
    pa, pb, pc = np.abs(p - left), np.abs(p - up), np.abs(p - upleft)
    paeth = np.where((pa <= pb) & (pa <= pc), left, np.where(pb <= pc, up, upleft))
    F = np.stack([rows, rows - left, rows - up, rows - ((left + up) >> 1), rows - paeth]) % 256
    signed = np.where(F > 127, F - 256, F)
    best = np.abs(signed).sum(axis=2).argmin(axis=0)
    out = F[best, np.arange(h)].astype(np.uint8)
    raw = np.concatenate([best[:, None].astype(np.uint8), out], 1).tobytes()

    def chunk(tag, data):
        return struct.pack('>I', len(data)) + tag + data + struct.pack('>I', zlib.crc32(tag + data) & 0xffffffff)
    ctype = {1: 0, 3: 2, 4: 6}[ch]
    with open(path, 'wb') as fh:
        fh.write(b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', w, h, 8, ctype, 0, 0, 0))
                 + chunk(b'IDAT', zlib.compress(raw, 9)) + chunk(b'IEND', b''))


def to_u8(x):
    return np.clip(np.round(x * 255.0), 0, 255).astype(np.uint8)


def lin_to_srgb(x):
    x = np.clip(x, 0.0, 1.0)
    return np.where(x <= 0.0031308, x * 12.92, 1.055 * np.power(x, 1 / 2.4) - 0.055)


class TexGen:
    def __init__(self, n, tile, seed):
        self.n, self.tile, self.seed, self.k = n, tile, seed, 0
        self.px = tile / n

    def rng(self):
        self.k += 1
        return np.random.default_rng(self.seed * 7919 + self.k)

    def noise(self, beta, fmin=1.0, sx=1.0, sy=1.0):
        """Tileable power-law noise, unit variance. sy > 1 stretches features along v."""
        n = self.n
        F = np.fft.fft2(self.rng().standard_normal((n, n)))
        fy = np.fft.fftfreq(n)[:, None] * n
        fx = np.fft.fftfreq(n)[None, :] * n
        f = np.sqrt((fx * sx) ** 2 + (fy * sy) ** 2)
        amp = np.power(np.maximum(f, 1e-9), -beta / 2.0)
        amp[f < fmin] = 0.0
        out = np.real(np.fft.ifft2(F * amp))
        out -= out.mean()
        return out / (out.std() + 1e-12)

    def worley(self, npts, sx=1.0, sy=1.0):
        """Tileable F1/F2 cellular distances (UV units)."""
        n = self.n
        pts = self.rng().random((npts, 2))
        g = (np.arange(n) + 0.5) / n
        X, Y = np.meshgrid(g, g)
        F1 = np.full((n, n), 9.0)
        F2 = np.full((n, n), 9.0)
        for px, py in pts:
            dx = np.abs(X - px)
            dx = np.minimum(dx, 1 - dx) * sx
            dy = np.abs(Y - py)
            dy = np.minimum(dy, 1 - dy) * sy
            d = np.sqrt(dx * dx + dy * dy)
            closer = d < F1
            F2 = np.where(closer, F1, np.minimum(F2, d))
            F1 = np.where(closer, d, F1)
        return F1, F2

    def pebbles(self, count, rmin, rmax):
        """Wrap-around dome stamps (radii in px); returns 0..1 heights."""
        n = self.n
        rng = self.rng()
        out = np.zeros((n, n))
        for _ in range(count):
            r = rng.uniform(rmin, rmax)
            cx, cy = rng.uniform(0, n, 2)
            R = int(math.ceil(r)) + 1
            ix = (int(cx) + np.arange(-R, R + 1)) % n
            iy = (int(cy) + np.arange(-R, R + 1)) % n
            ox = (np.arange(-R, R + 1) + int(cx) + 0.5 - cx)[None, :]
            oy = (np.arange(-R, R + 1) + int(cy) + 0.5 - cy)[:, None]
            d = np.sqrt((ox / r) ** 2 + (oy / (r * rng.uniform(0.6, 1.0))) ** 2)
            dome = np.sqrt(np.clip(1 - d * d, 0, 1)) * rng.uniform(0.5, 1.0)
            blk = out[np.ix_(iy, ix)]
            out[np.ix_(iy, ix)] = np.maximum(blk, dome)
        return out

    def normal(self, h):
        gx = (np.roll(h, -1, 1) - np.roll(h, 1, 1)) / (2 * self.px)
        gy = (np.roll(h, -1, 0) - np.roll(h, 1, 0)) / (2 * self.px)
        ln = np.sqrt(gx * gx + gy * gy + 1.0)
        return np.stack([-gx / ln, -gy / ln, 1.0 / ln], -1) * 0.5 + 0.5


def C(h):
    return np.array(lin(h))


def tex_mud_plaster(T):
    low, mid, fine, tone = T.noise(3.4), T.noise(2.2, 3), T.noise(0.8, 90), T.noise(3.0)
    F1, F2 = T.worley(34)
    crack = np.exp(-((F2 - F1) * T.n / 1.5) ** 2) * np.clip(T.noise(3.0) * 0.9 - 0.25, 0, 1)
    h = low * 1.6e-3 + mid * 0.5e-3 + fine * 0.07e-3 - crack * 0.9e-3
    k = (np.clip(0.5 + 0.35 * tone, 0, 1) * 0.35)[..., None]
    col = C('#a8201a') * (1 - k) + C('#8f3320') * k
    col = col * (1 + 0.09 * low + 0.04 * mid + 0.03 * fine)[..., None] * (1 - 0.45 * crack)[..., None]
    rough = 0.84 + 0.04 * mid + 0.025 * fine + 0.06 * crack
    return col, rough, h


def tex_thatch(T):
    strands, clumps = T.noise(1.5, 6, sy=16), T.noise(2.6, 2, sy=5)
    fine, sweep_ = T.noise(1.0, 80, sy=24), T.noise(3.0, sy=3)
    s = 0.55 * strands + 0.35 * clumps + 0.22 * fine
    h = s * 3.5e-3
    k = np.clip(0.5 + 0.3 * s + 0.1 * sweep_, 0, 1)[..., None]
    dark, mid_, hi = C('#1a0e08'), C('#3a2416'), C('#74502e')
    col = np.where(k < 0.5, dark + (mid_ - dark) * (k / 0.5), mid_ + (hi - mid_) * ((k - 0.5) / 0.5))
    rough = np.clip(0.82 - 0.08 * clumps + 0.05 * fine, 0.6, 0.95)
    return col, rough, h


def tex_earth(T):
    low, mid, fine = T.noise(3.2), T.noise(2.0, 4), T.noise(0.9, 100)
    peb = T.pebbles(700, 1.5, 4.5)
    F1, F2 = T.worley(26)
    crack = np.exp(-((F2 - F1) * T.n / 1.3) ** 2) * np.clip(T.noise(3.0) - 0.1, 0, 1)
    h = low * 2e-3 + mid * 0.6e-3 + fine * 0.08e-3 + peb * 1.2e-3 - crack * 1.2e-3
    col = C('#5c2e20') * (1 + 0.13 * low + 0.06 * mid + 0.04 * fine)[..., None]
    col = col + (C('#7a5040') - col) * (np.clip(peb, 0, 1) * 0.7)[..., None]
    col = col * (1 - 0.5 * crack)[..., None]
    rough = np.clip(0.86 + 0.04 * mid - 0.05 * peb, 0, 1)
    return col, rough, h


def tex_ground(T):
    low, mid, fine, clods = T.noise(3.0), T.noise(2.0, 5), T.noise(1.0, 120), T.noise(2.4, 10)
    peb = T.pebbles(1200, 1.2, 4.5)
    dips = T.noise(2.2, 4)
    # wet spots: many small pools rather than a few big blotches, so the 4 m tile doesn't show
    wet = np.clip((-0.95 - dips - 0.3 * low) * 0.9, 0, 1)
    h = (low * 4e-3 + mid * 2e-3 + clods * 1e-3 + fine * 0.12e-3 + peb * 3e-3 - wet * 1.5e-3) * (1 - 0.6 * wet)
    col = C(HEX['ground']) + (C('#241010') - C(HEX['ground'])) * np.clip(0.5 + 0.25 * mid, 0, 1)[..., None]
    col = col * (1 + 0.06 * low + 0.04 * fine)[..., None]
    col = col + (C('#4a3230') - col) * (np.clip(peb, 0, 1) * 0.6)[..., None]
    col = col * (1 - 0.22 * wet)[..., None]
    rough = np.clip(0.8 + 0.05 * fine - 0.68 * wet, 0.1, 1)
    return col, rough, h


def tex_wood(T, base_hex, dark_hex):
    warp, grain = T.noise(3.0, sy=4), T.noise(1.3, 8, sy=12)
    x = ((np.arange(T.n) + 0.5) / T.n)[None, :]
    rings = np.sin(2 * np.pi * (26 * x + 0.6 * warp))
    F1, _ = T.worley(70, sy=0.4)
    facet = F1 / F1.max()                         # adze facets of hand-carved wood
    h = rings * 0.08e-3 + grain * 0.2e-3 - facet ** 2 * 0.9e-3
    k = np.clip(0.55 + 0.1 * rings + 0.22 * grain, 0, 1)[..., None]
    col = C(dark_hex) + (C(base_hex) - C(dark_hex)) * k
    col = col * (1 + 0.08 * T.noise(3.0))[..., None]
    rough = np.clip(0.58 + 0.06 * grain + 0.05 * facet, 0, 1)
    return col, rough, h


def tex_stone(T):
    low, grain, mid = T.noise(3.0), T.noise(1.1, 30), T.noise(2.0, 6)
    g = (np.arange(T.n) + 0.5) / T.n
    X, Y = np.meshgrid(g, g)
    tool = np.sin(2 * np.pi * (14 * (X + Y) + 0.6 * T.noise(3.0)))
    pits = T.pebbles(450, 1.0, 3.0)
    h = low * 1.2e-3 + mid * 0.4e-3 + grain * 0.1e-3 + tool * 0.18e-3 - pits * 0.5e-3
    col = C(HEX['pillar']) + (C('#4a3a34') - C(HEX['pillar'])) * np.clip(0.5 + 0.3 * mid, 0, 1)[..., None]
    col = col * (1 + 0.12 * low + 0.05 * grain)[..., None] * (1 - 0.3 * pits)[..., None]
    rough = np.clip(0.76 + 0.05 * grain + 0.08 * pits, 0, 1)
    return col, rough, h


def tex_bark(T):
    F1, F2 = T.worley(110, sy=0.5)
    edge = F2 - F1
    groove = np.exp(-(edge * T.n / 2.2) ** 2)
    dome = np.clip(edge * T.n / 18.0, 0, 1) ** 0.6
    fine, low = T.noise(1.0, 60), T.noise(3.0)
    h = dome * 3e-3 - groove * 2.5e-3 + fine * 0.15e-3
    ashk = np.clip(dome ** 2 * (0.5 + 0.5 * low) * 0.8 + 0.1 * fine, 0, 1)[..., None]
    col = C('#140a0b') + (C('#3b3431') - C('#140a0b')) * ashk
    col = col + (C('#2a0c08') - col) * (groove * 0.6)[..., None]
    rough = np.clip(0.9 - 0.25 * groove, 0, 1)
    return col, rough, h


def tex_ember(T):
    F1, F2 = T.worley(80, sy=0.6)
    edge = F2 - F1
    glow = np.exp(-(edge * T.n / 1.7) ** 2)
    flick = np.clip(1.6 * (0.5 + 0.45 * T.noise(2.8)) - 0.75, 0, 1)  # most cracks have gone cold
    dome = np.clip(edge * T.n / 16.0, 0, 1) ** 0.6
    h = dome * 2.5e-3 - glow * 2e-3
    col = C('#120808') + (C('#3a0c06') - C('#120808')) * glow[..., None]
    g = glow * flick
    emis = (C('#ff5a1a') + (C('#ffb35a') - C('#ff5a1a')) * (g ** 2)[..., None]) * g[..., None]
    rough = np.clip(0.88 - 0.3 * glow, 0, 1)
    return col, rough, h, emis


def tex_scar(nu=512, nv=64, seed=5):
    """Glowing lightning crack: u along the crack (tileable), v across it (0..1)."""
    rng = np.random.default_rng(seed)
    F = np.fft.fft(rng.standard_normal(nu))
    f = np.abs(np.fft.fftfreq(nu) * nu)
    amp = np.where(f < 1, 0, np.power(np.maximum(f, 1e-9), -0.9))
    fl = np.real(np.fft.ifft(F * amp))
    fl = (fl - fl.mean()) / fl.std()
    v = ((np.arange(nv) + 0.5) / nv)[:, None]
    wob = 0.06 * fl[None, :]
    prof = np.exp(-((v - 0.5 - wob) / 0.17) ** 2)
    core = np.exp(-((v - 0.5 - wob) / 0.055) ** 2)
    edge = np.clip(v / 0.12, 0, 1) * np.clip((1 - v) / 0.12, 0, 1)
    flick = np.clip(0.8 + 0.2 * fl, 0.5, 1.1)[None, :]
    e = (C(HEX['crack'])[None, None, :] * prof[..., None]
         + (C(HEX['crack_core']) - C(HEX['crack']))[None, None, :] * core[..., None]) * (edge * flick)[..., None]
    return np.clip(e, 0, 1)


