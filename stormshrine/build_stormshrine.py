KP = 0.62 / 88.0        # pillar: top 88 px wide (x 1446..1534) -> 0.62 m


def pillar_section(w, c):
    return [(w - c, -w), (w, -w + c), (w, w - c), (w - c, w), (-w + c, w), (-w, w - c), (-w, -w + c), (-w + c, -w)]


def build_pillar(coll):
    """Stormshrine_SnakePillar (SVG x 1440..1540): tapered carved stone shaft,
    cap slab, red snake outlined in white zigzagging down the front with a
    white head, red and white cloth bands and a hanging red cloth tail."""
    mb = MB()
    stone, W, R = ASSET_PREFIX + 'Stone_Pillar', ASSET_PREFIX + 'Kaolin_White', ASSET_PREFIX + 'Pigment_Red'
    cred, cwhite = ASSET_PREFIX + 'Cloth_Red', ASSET_PREFIX + 'Cloth_White'
    h_shaft = (900 - 384) * KP              # 3.64 to the underside of the cap
    w0, w1 = 0.35, 0.31
    wz = lambda z: w0 + (w1 - w0) * z / h_shaft
    zb = -0.05
    isl = mb.island()
    lo = [mb.vert((x, y, zb)) for x, y in pillar_section(wz(zb), 0.04)]
    hi = [mb.vert((x, y, h_shaft)) for x, y in pillar_section(w1, 0.04)]
    sec = pillar_section(w0, 0.04)
    acc = 0.0
    for k in range(8):
        k1 = (k + 1) % 8
        d = math.dist(sec[k], sec[k1])
        mb.face([lo[k], lo[k1], hi[k1], hi[k]], [(acc, 0), (acc + d, 0), (acc + d, h_shaft - zb), (acc, h_shaft - zb)],
                stone, False, isl)
        acc += d
    # cap slab (SVG rect 1432,364 116x20)
    cap_w = 116 * KP / 2
    ring_b = rrect(cap_w, cap_w, 0.03, 1, 1, 2)
    ring_t = rrect(cap_w - 0.025, cap_w - 0.025, 0.03, 1, 1, 2)
    z_top = (900 - 364) * KP
    vb = [mb.vert((x, y, h_shaft)) for x, y in ring_b]
    vm = [mb.vert((x, y, z_top - 0.025)) for x, y in ring_b]
    vt = [mb.vert((x, y, z_top)) for x, y in ring_t]
    n = len(ring_b)
    ci, si = mb.island(), mb.island()
    mb.face(vb[::-1], [(x, -y) for x, y in ring_b][::-1], stone, False, mb.island())
    mb.face(vt, ring_t, stone, False, ci)
    acc = 0.0
    for k in range(n):
        k1 = (k + 1) % n
        d = math.dist(ring_b[k], ring_b[k1])
        mb.face([vb[k], vb[k1], vm[k1], vm[k]], [(acc, 0), (acc + d, 0), (acc + d, 0.115), (acc, 0.115)], stone, False, si)
        mb.face([vm[k], vm[k1], vt[k1], vt[k]], [(acc, 0.15), (acc + d, 0.15), (acc + d, 0.19), (acc, 0.19)], stone,
                False, si)
        acc += d
    # front face map (outward -Y), following the taper
    fm = lambda s, t, h: Vector((s, -(wz(t) + h), t))
    loc = lambda x, y: ((x - 1490) * KP, (900 - y) * KP)
    zz = [(1490, 420), (1470, 450), (1510, 480), (1470, 510), (1510, 540), (1470, 570), (1510, 600), (1470, 630),
          (1500, 660)]
    snake = [loc(x, y) for x, y in zz]
    relief_stroke(mb, snake, 7 * KP, 0.012, fm, W)
    # red core, stopped 1 cm short of the white outline's ends so their end caps don't share a plane
    core = [Vector(p) for p in snake]
    core[0] = core[0] + (core[1] - core[0]).normalized() * 0.01
    core[-1] = core[-1] + (core[-2] - core[-1]).normalized() * 0.01
    relief_stroke(mb, [tuple(p) for p in core], 3 * KP, 0.018, fm, R)
    hx_, hy_ = loc(1492, 414)
    relief_fill(mb, ellipse(hx_, hy_, 12 * KP, 8 * KP, 14), 0.016, fm, W)
    # cloth bands (SVG y 700..722 red, 722..734 white): sleeves round the shaft;
    # where they meet, neither gets a ring face (they would sit on top of each other)
    for (ya, yb), mat, top, bottom in (((722, 700), cred, True, False), ((734, 722), cwhite, False, True)):
        za_, zb2 = (900 - ya) * KP, (900 - yb) * KP
        isl = mb.island()
        so_a = pillar_section(wz(za_) + 0.018, 0.05)
        so_b = pillar_section(wz(zb2) + 0.018, 0.05)
        si_a = pillar_section(wz(za_) - 0.003, 0.04)
        si_b = pillar_section(wz(zb2) - 0.003, 0.04)
        oa = [mb.vert((x, y, za_)) for x, y in so_a]
        ob = [mb.vert((x, y, zb2)) for x, y in so_b]
        ia = [mb.vert((x, y, za_)) for x, y in si_a]
        ib = [mb.vert((x, y, zb2)) for x, y in si_b]
        acc = 0.0
        hgt = zb2 - za_
        for k in range(8):
            k1 = (k + 1) % 8
            d = math.dist(so_a[k], so_a[k1])
            mb.face([oa[k], oa[k1], ob[k1], ob[k]], [(acc, 0), (acc + d, 0), (acc + d, hgt), (acc, hgt)], mat, False, isl)
            if top:
                mb.face([ob[k], ob[k1], ib[k1], ib[k]], [(acc, hgt + 0.05), (acc + d, hgt + 0.05),
                                                         (acc + d, hgt + 0.08), (acc, hgt + 0.08)], mat, False, isl)
            if bottom:
                mb.face([oa[k], ia[k], ia[k1], oa[k1]], [(acc, -0.05), (acc, -0.08), (acc + d, -0.08),
                                                         (acc + d, -0.05)], mat, False, isl)
            acc += d
    # hanging red tail (SVG 1450,734 1440,790 1462,780 1468,734)
    tail = MB()
    outline = [loc(1450, 734), loc(1440, 790), loc(1462, 780), loc(1468, 734)]
    extrude_shape(tail, outline, 0.008, cred, cred)
    z_top_tail = (900 - 734) * KP
    tail.transform(translate(0, -(wz(z_top_tail) + 0.028), 0) @ translate(0, 0, z_top_tail)
                   @ Matrix.Rotation(math.radians(-7), 4, 'X') @ translate(0, 0, -z_top_tail))
    mb.merge(tail)
    mb.transform(translate(*PILLAR_POS) @ rot_z(math.radians(-20)))   # snake face turned toward the floor
    return mb_to_object(mb, ASSET_PREFIX + 'SnakePillar', coll)


def build_tree(coll):
    """Stormshrine_SplitTree (SVG x -20..190): a dead trunk split by lightning
    into a tall spire and a shorter fork; the split faces smoulder (emissive
    embers), with a glowing fissure running down the trunk."""
    mb = MB()
    bark, ember = ASSET_PREFIX + 'Bark_Charred', ASSET_PREFIX + 'Ember'
    rz = [(-0.15, 0.95), (0.1, 0.78), (0.4, 0.62), (0.8, 0.55), (1.3, 0.51), (1.9, 0.48), (2.5, 0.46), (3.1, 0.44),
          (3.6, 0.43), (3.85, 0.42)]
    NS = 22
    noise = lambda th, z: 1 + 0.07 * math.sin(3 * th + 0.8) + 0.05 * math.sin(5 * th + 2.1 + 0.6 * z) \
        + 0.03 * math.sin(9 * th + 1.3 * z)
    sec = circle(NS)
    path = [Vector((0, 0, z)) for z, _ in rz]
    radii = [r for _, r in rz]
    rings = sweep(mb, path, radii, sec, bark, smooth=True, ref=Vector((1, 0, 0)),
                  radial_fn=lambda i, k: noise(2 * math.pi * k / NS, rz[i][0]))
    # charred, glowing crotch where the halves part
    top = rings[-1]
    ci = mb.island()
    cen = mb.vert((0, 0, rz[-1][0] + 0.02))
    for k in range(NS):
        k1 = (k + 1) % NS
        a, b = mb.v[top[k]], mb.v[top[k1]]
        mb.face([top[k], top[k1], cen], [(a.x, a.y), (b.x, b.y), (0, 0)], ember, False, ci)
    # the two halves: D sections with the flat (split) face toward each other
    def half(sign, pts, rads):
        arc = [(sign * -math.cos(a), math.sin(a)) for a in
               (math.radians(d) for d in range(-90, 91, 20))]   # arc away from the split
        flat = [(0.0, 1.0 - 2.0 * k / 3) for k in (1, 2)]
        secD = ccw(arc + flat if sign > 0 else arc + flat)
        mats = []
        for k in range(len(secD)):
            a, b = secD[k], secD[(k + 1) % len(secD)]
            mats.append(ember if abs(a[0]) < 1e-6 and abs(b[0]) < 1e-6 else bark)
        sweep(mb, pts, rads, secD, mats, smooth=True, ref=Vector((1, 0, 0)))
    half(1, [Vector(p) for p in ((-0.01, 0, 3.7), (-0.1, 0, 4.6), (-0.3, 0.03, 5.6), (-0.48, 0.05, 6.5),
                                 (-0.55, 0.05, 7.25))], [0.42, 0.35, 0.25, 0.14, 0.0])
    half(-1, [Vector(p) for p in ((0.01, 0, 3.7), (0.25, 0, 4.4), (0.62, -0.03, 5.1), (0.95, -0.05, 5.6),
                                  (1.12, -0.05, 5.95))], [0.42, 0.32, 0.22, 0.11, 0.0])
    # big lower branch to the left, two broken stubs, root flares
    sweep(mb, [Vector(p) for p in ((-0.2, 0, 3.2), (-0.9, 0, 3.55), (-1.5, -0.05, 4.1), (-1.95, -0.08, 4.65),
                                   (-2.1, -0.08, 4.85))], [0.17, 0.14, 0.10, 0.06, 0.0], circle(8), bark,
          ref=Vector((0, 0, 1)))
    for p0, p1, r0, r1 in (((0.2, -0.15, 2.1), (0.62, -0.55, 2.35), 0.10, 0.08),
                           ((-0.05, 0.25, 2.7), (-0.2, 0.85, 2.95), 0.08, 0.06)):
        sweep(mb, [Vector(p0), Vector(p1)], [r0, r1], circle(8), bark, cap_end=True, cap_mat=ember,
              ref=Vector((0, 0, 1)))
    for k in range(5):
        th = 0.5 + 2 * math.pi * k / 5
        c, s = math.cos(th), math.sin(th)
        sweep(mb, [Vector((0.45 * c, 0.45 * s, 0.4)), Vector((0.95 * c, 0.95 * s, 0.13)),
                   Vector((1.5 * c, 1.5 * s, -0.12))], [0.24, 0.16, 0.07], circle(8), bark, cap_end=True,
              ref=Vector((0, 0, 1)))
    # glowing fissure down the trunk (+X flank)
    rfun_t = lambda z, th: interp(rz, z) * noise(th, z)
    th0 = 0.05
    fis = [(0.05 * math.sin(z * 2.3), z) for z in np.linspace(3.75, 0.7, 14)]

    def fmap(s, t, h, th0=th0):
        th = th0 + s / 0.45
        r = rfun_t(t, th) + h
        return Vector((r * math.cos(th), r * math.sin(th), t))
    relief_stroke(mb, fis, 0.05, 0.018, fmap, ember, embed=0.06)
    mb.transform(translate(*TREE_POS) @ rot_z(math.radians(-40)))
    return mb_to_object(mb, ASSET_PREFIX + 'SplitTree', coll)


