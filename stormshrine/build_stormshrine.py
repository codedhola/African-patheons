def bolt_points(start, end, rnd, depth=5, disp=0.22):
    """Jagged lightning path by midpoint displacement in the X-Z plane."""
    pts = [Vector(start), Vector(end)]
    for _ in range(depth):
        out = [pts[0]]
        for a, b in zip(pts, pts[1:]):
            m = (a + b) / 2
            seg = b - a
            side = Vector((-seg.z, 0.0, seg.x)).normalized()
            out += [m + side * rnd.uniform(-1, 1) * seg.length * disp, b]
        pts = out
    return pts


