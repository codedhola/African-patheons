def hex_srgb(h):
    h = h.lstrip('#')
    return tuple(int(h[i:i + 2], 16) / 255.0 for i in (0, 2, 4))


def s2l(c):
    if isinstance(c, (tuple, list)):
        return tuple(s2l(x) for x in c)
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4


def lin(h):
    return s2l(hex_srgb(h))


def bez(P, t):
    """Cubic Bezier point for 4 control points (2-D tuples)."""
    a = (1 - t) ** 3
    b = 3 * (1 - t) ** 2 * t
    c = 3 * (1 - t) * t ** 2
    d = t ** 3
    return (a * P[0][0] + b * P[1][0] + c * P[2][0] + d * P[3][0],
            a * P[0][1] + b * P[1][1] + c * P[2][1] + d * P[3][1])


def bez_path(segments, n=8):
    """Sample a chain of cubic segments [(p0, c1, c2, p1), ...] into points."""
    pts = []
    for si, P in enumerate(segments):
        for k in range(n + 1):
            if k == 0 and si > 0:
                continue
            pts.append(bez(P, k / n))
    return pts


def signed_area(pts):
    return 0.5 * sum(pts[i][0] * pts[(i + 1) % len(pts)][1] - pts[(i + 1) % len(pts)][0] * pts[i][1]
                     for i in range(len(pts)))


def ccw(pts):
    return list(pts) if signed_area(pts) > 0 else list(reversed(pts))


def interp(table, x):
    """Piecewise-linear lookup in a list of (x, y) sorted by x."""
    if x <= table[0][0]:
        return table[0][1]
    for (x0, y0), (x1, y1) in zip(table, table[1:]):
        if x <= x1:
            return y0 + (y1 - y0) * (x - x0) / (x1 - x0)
    return table[-1][1]


def rot_z(a):
    return Matrix.Rotation(a, 4, 'Z')


def translate(x, y, z=0.0):
    return Matrix.Translation((x, y, z))


